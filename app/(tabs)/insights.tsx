import { useRouter } from 'expo-router';
import { useMemo, useState } from 'react';
import { Pressable, View } from 'react-native';

import { Icon } from '@/components/Icon';
import {
  Badge,
  Card,
  EmptyState,
  ErrorState,
  InfoNote,
  Screen,
  SegmentedControl,
  Skeleton,
  Text,
} from '@/components/ui';
import { useRangeJournal } from '@/features/journal';
import { generateInsights } from '@/features/memory/insights';
import { LOCAL_USER_ID } from '@/features/journal';
import { addDaysToKey, formatDayLabel, todayKey } from '@/lib/date';
import { usePreferencesStore } from '@/store/preferencesStore';
import { useTheme } from '@/theme';

type Period = '7' | '30';

const PERIOD_OPTIONS = [
  { value: '7' as const, label: 'Last 7 days' },
  { value: '30' as const, label: 'Last 30 days' },
];

export default function InsightsScreen() {
  const theme = useTheme();
  const router = useRouter();
  const [period, setPeriod] = useState<Period>('7');

  const foodMemoryEnabled = usePreferencesStore(
    (state) => state.preferences.foodMemoryEnabled,
  );

  const endKey = todayKey();
  const startKey = addDaysToKey(endKey, period === '7' ? -6 : -29);
  const { entries, loading, error, reload } = useRangeJournal(startKey, endKey);

  const { insights, sufficiency } = useMemo(
    () =>
      generateInsights(entries, LOCAL_USER_ID, {
        periodStart: startKey,
        periodEnd: endKey,
      }),
    [entries, startKey, endKey],
  );

  return (
    <Screen
      edges={{ top: true }}
      refreshing={loading}
      onRefresh={reload}
      contentStyle={{ gap: theme.spacing.lg }}
    >
      <View style={{ gap: theme.spacing.sm }}>
        <Text variant="title">Insights</Text>
        <Text variant="bodySm" color="textMuted">
          Patterns counted from the meals you saved. Nothing here is guessed or
          generated by a model.
        </Text>
      </View>

      {!foodMemoryEnabled ? (
        <>
          <InfoNote
            title="Food Memory is turned off"
            body="Insights are built from your saved meal history. Turn Food Memory on in Profile to see them."
            tone="neutral"
          />
          <Card variant="soft" padding="none">
            <EmptyState
              title="No patterns shown"
              body="Your meals are still being saved; they just are not being analysed."
              illustration={<Icon name="sparkle" size={44} color="textMuted" />}
              actionLabel="Open Profile"
              onAction={() => router.push('/(tabs)/profile')}
            />
          </Card>
        </>
      ) : (
        <>
          <SegmentedControl
            options={PERIOD_OPTIONS}
            value={period}
            onChange={setPeriod}
            accessibilityLabel="Insight period"
          />

          <Text variant="caption" color="textMuted">
            {formatDayLabel(startKey)} TO {formatDayLabel(endKey)}
          </Text>

          {error ? (
            <ErrorState
              message={error.message}
              detail={error.detail}
              onRetry={error.retryable ? reload : undefined}
            />
          ) : loading && entries.length === 0 ? (
            <View style={{ gap: theme.spacing.md }}>
              <Skeleton height={130} radius={theme.radius.lg} />
              <Skeleton height={130} radius={theme.radius.lg} />
            </View>
          ) : !sufficiency.sufficient ? (
            <Card variant="soft" padding="none">
              <EmptyState
                title="Not enough logged yet"
                body={`${sufficiency.requirement} So far this period has ${sufficiency.entryCount} meal${
                  sufficiency.entryCount === 1 ? '' : 's'
                } across ${sufficiency.daysLogged} day${
                  sufficiency.daysLogged === 1 ? '' : 's'
                }.`}
                illustration={<Icon name="insights" size={44} color="primary" />}
                actionLabel="Add a meal"
                onAction={() => router.push('/entry/new')}
              />
            </Card>
          ) : (
            <View style={{ gap: theme.spacing.md }}>
              {insights.map((insight) => (
                <InsightCard
                  key={insight.id}
                  headline={insight.headline}
                  detail={insight.detail}
                  method={insight.evidence.method}
                  entryCount={insight.evidence.entryCount}
                />
              ))}
            </View>
          )}
        </>
      )}
    </Screen>
  );
}

/** One insight, with its working available on demand. */
function InsightCard({
  headline,
  detail,
  method,
  entryCount,
}: {
  headline: string;
  detail: string;
  method: string;
  entryCount: number;
}) {
  const theme = useTheme();
  const [showMethod, setShowMethod] = useState(false);

  return (
    <Card padding="lg" style={{ gap: theme.spacing.sm }}>
      <Badge
        label={`From ${entryCount} saved meal${entryCount === 1 ? '' : 's'}`}
        tone="primary"
      />
      <Text variant="heading">{headline}</Text>
      <Text variant="bodySm" color="textMuted">
        {detail}
      </Text>

      <Pressable
        onPress={() => setShowMethod((open) => !open)}
        accessibilityRole="button"
        accessibilityLabel={showMethod ? 'Hide how this was counted' : 'Show how this was counted'}
        accessibilityState={{ expanded: showMethod }}
        style={{
          flexDirection: 'row',
          alignItems: 'center',
          gap: theme.spacing.xs,
          paddingVertical: theme.spacing.sm,
        }}
      >
        <Icon name="info" size={16} color="primaryOnSoft" />
        <Text variant="bodySmStrong" color="primaryOnSoft">
          {showMethod ? 'Hide how this was counted' : 'How was this counted?'}
        </Text>
      </Pressable>

      {showMethod ? <InfoNote body={method} tone="neutral" /> : null}
    </Card>
  );
}
